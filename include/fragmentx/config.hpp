#pragma once

/// @file config.hpp
/// @brief FragmentX allocator and capture configuration.

#include <cstddef>
#include <cstdint>
#include <string>
#include <string_view>

namespace fragmentx {

// ─── Enumerations ───────────────────────────────────────────────────────────

/// @brief Verbosity level for FragmentX internal logging.
enum class LogLevel : uint8_t {
  Silent  = 0, ///< No output.
  Error   = 1, ///< Errors only.
  Warning = 2, ///< Errors and warnings.
  Info    = 3, ///< General operational messages.
  Debug   = 4, ///< Detailed internal diagnostics.
};

/// @brief Capture mode controlling how allocation events are intercepted.
enum class CaptureMode : uint8_t {
  /// Explicit FragmentX allocation APIs (fxalloc / fxfree). Zero overhead when
  /// capture is disabled; requires source-level integration.
  Instrumented,

  /// Intercepts malloc/free/realloc/calloc via LD_PRELOAD on Linux.
  /// Transparent to the application; Linux only.
  Interposition,

  /// Events are recorded directly by FragmentX's own allocator runtime.
  /// Only valid when the FragmentX allocator is in use.
  CustomAllocator,

  /// No live capture; events are replayed from an existing trace file.
  /// Used by the optimizer and benchmark engine.
  Replay,
};

/// @brief Controls how the allocator responds to out-of-memory conditions.
enum class OomBehavior : uint8_t {
  ReturnNull,  ///< Return nullptr on allocation failure (default).
  Throw,       ///< Throw std::bad_alloc on allocation failure.
  Abort,       ///< Call std::abort on allocation failure.
};

// ─── Config ─────────────────────────────────────────────────────────────────

/// @brief Configuration for the FragmentX allocator and capture subsystem.
///
/// Construct a Config, adjust fields as needed, then pass it to the Allocator
/// or CaptureSession constructor.
///
/// @code
/// fragmentx::Config cfg;
/// cfg.policy_path          = "my-policy.json";
/// cfg.enable_capture       = true;
/// cfg.capture_output_path  = "workload.fxtrace";
/// fragmentx::Allocator allocator(cfg);
/// @endcode
struct Config {
  // ── Policy ───────────────────────────────────────────────────────────────

  /// Path to a JSON policy file generated by the FragmentX optimizer.
  /// Empty string means use the built-in default routing policy.
  std::string policy_path;

  // ── Allocator ────────────────────────────────────────────────────────────

  /// Size in bytes of each memory region acquired from the OS.
  /// Must be a multiple of the system page size (4096 on most platforms).
  /// Default: 64 MiB.
  std::size_t region_size = 64ULL * 1024 * 1024;

  /// Maximum number of arenas the allocator may create concurrently.
  /// Each arena operates independently to reduce thread contention.
  /// Default: 16.
  std::size_t max_arenas = 16;

  /// Number of blocks cached in each thread-local free list per size class.
  /// Higher values reduce lock contention at the cost of per-thread memory.
  /// Default: 64.
  std::size_t thread_local_cache_size = 64;

  /// When true, the allocator falls back to the system malloc/free for
  /// allocations that cannot be served from FragmentX regions (e.g. very large
  /// allocations or during initialization). When false, OOM behavior applies.
  bool fallback_to_system = true;

  /// Controls allocator response when memory cannot be obtained.
  OomBehavior oom_behavior = OomBehavior::ReturnNull;

  /// Minimum alignment guaranteed for every allocation, in bytes.
  /// Must be a power of two and at least alignof(std::max_align_t).
  /// Default: 16 (suitable for SIMD on most platforms).
  std::size_t default_alignment = 16;

  // ── Capture ───────────────────────────────────────────────────────────────

  /// Enable allocation event recording. Incurs per-allocation overhead.
  bool enable_capture = false;

  /// File path for the binary trace output (.fxtrace).
  std::string capture_output_path = "fragmentx.fxtrace";

  /// Capture mode (see CaptureMode).
  CaptureMode capture_mode = CaptureMode::Instrumented;

  /// Sampling rate: record 1 in every N allocations. 1 = record all.
  /// Higher values reduce overhead at the cost of statistical fidelity.
  uint32_t capture_sample_rate = 1;

  /// Capacity of the lock-free ring buffer used to pass events from
  /// allocation threads to the writer thread. Must be a power of two.
  /// Default: 65536 entries.
  uint32_t capture_ring_buffer_capacity = 65536;

  // ── Logging ───────────────────────────────────────────────────────────────

  /// Verbosity of internal FragmentX log output.
  LogLevel log_level = LogLevel::Warning;

  // ── Validation ────────────────────────────────────────────────────────────

  /// Validate the configuration, returning an error string if invalid.
  /// Returns an empty string when the configuration is valid.
  [[nodiscard]] std::string validate() const;
};

} // namespace fragmentx

