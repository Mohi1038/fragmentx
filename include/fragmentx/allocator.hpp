#include <fragmentx/config.hpp>
#include <fragmentx/lifetime.hpp>
#include <fragmentx/statistics.hpp>
#include <fragmentx/policy.hpp>
#include <cstddef>
#include <cstdint>
#include <string>
#include <memory>

namespace fragmentx {

// ─── Allocator ──────────────────────────────────────────────────────────────

/// @brief The FragmentX policy-driven memory allocator.
///
/// Provides arena-based allocation with optional policy-guided routing.
/// Thread-safe by default; each thread uses a thread-local free-list cache
/// to minimize contention on the global arena structures.
///
/// @par Basic usage
/// @code
/// fragmentx::Config cfg;
/// cfg.policy_path = "optimized.json";
/// fragmentx::Allocator alloc(cfg);
///
/// void* p = alloc.allocate(256);
/// // ... use p ...
/// alloc.deallocate(p);
/// @endcode
///
/// @par Typed allocation with lifetime hint
/// @code
/// auto* req = alloc.allocate_typed<Request>(LifetimeHint::ShortLived);
/// // ... use req ...
/// alloc.destroy_typed(req);
/// @endcode
class Allocator {
public:
  /// @brief Construct an allocator with the given configuration.
  /// @throws std::runtime_error if the configuration is invalid or if the
  ///         initial memory region cannot be obtained from the OS.
  explicit Allocator(const Config& config = Config{});

  ~Allocator();

  // Non-copyable; move-constructible for embedding in other classes.
  Allocator(const Allocator&)            = delete;
  Allocator& operator=(const Allocator&) = delete;
  Allocator(Allocator&&)                 noexcept;
  Allocator& operator=(Allocator&&)      noexcept;

  // ── Core allocation API ───────────────────────────────────────────────

  /// @brief Allocate @p size bytes with @p alignment alignment.
  ///
  /// @param size       Requested byte count. 0 returns a unique non-null
  ///                   pointer that must be passed to deallocate().
  /// @param alignment  Must be a power of two. Defaults to Config::default_alignment.
  /// @return Pointer to allocated memory, or nullptr on failure (unless
  ///         OomBehavior::Throw or OomBehavior::Abort is configured).
  [[nodiscard]] void* allocate(std::size_t size,
                               std::size_t alignment = 0) noexcept;

  /// @brief Deallocate memory previously returned by allocate() or reallocate().
  /// Passing nullptr is a no-op.
  void deallocate(void* ptr) noexcept;

  /// @brief Resize an allocation.
  ///
  /// Attempts in-place resize first. Falls back to allocate + memcpy + free.
  /// @param ptr     Pointer previously returned by allocate(). nullptr is treated
  ///                as a fresh allocate(new_size).
  /// @param new_size New requested size. 0 is treated as deallocate(ptr).
  [[nodiscard]] void* reallocate(void* ptr, std::size_t new_size) noexcept;

  // ── Lifetime-hinted typed allocation ─────────────────────────────────

  /// @brief Allocate storage for type T with an optional lifetime hint.
  /// @note  Does NOT call T's constructor — use placement new separately.
  template <typename T>
  [[nodiscard]] T* allocate_typed(LifetimeHint hint = LifetimeHint::Unknown,
                                  std::size_t count = 1) noexcept {
    return static_cast<T*>(
        allocate_with_hint(sizeof(T) * count, alignof(T), hint));
  }

  /// @brief Deallocate typed storage (does NOT call destructor).
  template <typename T>
  void deallocate_typed(T* ptr) noexcept {
    deallocate(static_cast<void*>(ptr));
  }

  /// @brief Construct an object using placement new and allocate_typed.
  template <typename T, typename... Args>
  [[nodiscard]] T* construct(LifetimeHint hint, Args&&... args) {
    T* ptr = allocate_typed<T>(hint);
    if (ptr) {
      return ::new (ptr) T(std::forward<Args>(args)...);
    }
    return nullptr;
  }

  /// @brief Destroy an object: calls destructor then deallocates.
  template <typename T>
  void destroy(T* ptr) noexcept {
    if (ptr) {
      ptr->~T();
      deallocate_typed(ptr);
    }
  }

  // ── Policy management ─────────────────────────────────────────────────

  /// @brief Load and apply an allocation policy from a JSON file.
  /// @param path  Path to the policy JSON file generated by the optimizer.
  /// @return      true if the policy was loaded and applied successfully.
  bool load_policy(const std::string& path);

  /// @brief Apply an already-parsed AllocationPolicy.
  bool apply_policy(const AllocationPolicy& policy);

  /// @brief Remove the active policy and revert to default routing.
  void clear_policy() noexcept;

  /// @return true if a non-default policy is currently active.
  [[nodiscard]] bool has_policy() const noexcept;

  /// @return The currently active policy, or empty string if none.
  [[nodiscard]] std::string active_policy_name() const noexcept;

  // ── Statistics ────────────────────────────────────────────────────────

  /// @brief Return a point-in-time statistics snapshot.
  [[nodiscard]] AllocatorStatistics statistics() const noexcept;

  /// @brief Reset all statistics counters to zero.
  void reset_statistics() noexcept;

  /// @brief Flush all thread-local caches to the global arena structures.
  /// Call this before taking a statistics snapshot for accurate free-list counts.
  void flush_thread_caches() noexcept;

private:
  [[nodiscard]] void* allocate_with_hint(std::size_t size,
                                         std::size_t alignment,
                                         LifetimeHint hint) noexcept;

  struct Impl;
  std::unique_ptr<Impl> impl_;
};

} // namespace fragmentx

